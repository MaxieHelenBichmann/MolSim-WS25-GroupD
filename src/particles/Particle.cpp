using namespace mol_sim;

Particle::Particle(int type_arg)
    : x(R3{0., 0., 0.}),
      f(R3{0., 0., 0.}),
      epsilon(0.0),
      sigma(0.0),
      v(R3{0., 0., 0.}),
      m(0.0),
      old_x(R3{0., 0., 0.}),
      old_f(R3{0., 0., 0.}),
      type(type_arg),
      reference_position(R3{0., 0., 0.}),
      neighbors{std::nullopt, std::nullopt, std::nullopt, std::nullopt,
                std::nullopt, std::nullopt, std::nullopt, std::nullopt} {
    mirror_positions.reserve(4);  // Reserve space for up to 4 mirrors
    SPDLOG_DEBUG("Particle generated!");
}

Particle::Particle(const Particle& other) {
    x = other.x;
    v = other.v;
    f = other.f;
    epsilon = other.epsilon;
    sigma = other.sigma;
    old_x = other.old_x;
    old_f = other.old_f;
    m = other.m;
    type = other.type;
    mirror_locations = other.mirror_locations;
    neighbors.fill(std::nullopt);  // Don't copy neighbor indices - would break reciprocal relationships
    mirror_positions = other.mirror_positions;
    reference_position = other.reference_position;
    SPDLOG_DEBUG("Particle generated by copy!");
}

Particle& Particle::operator=(const Particle& other) {
    if (this == &other) {  // handle self-assignment
        return *this;
    }
    x = other.x;
    v = other.v;
    f = other.f;
    epsilon = other.epsilon;
    sigma = other.sigma;
    old_x = other.old_x;
    old_f = other.old_f;
    m = other.m;
    type = other.type;
    mirror_locations = other.mirror_locations;
    neighbors.fill(std::nullopt);  // Don't copy neighbor indices - would break reciprocal relationships
    mirror_positions = other.mirror_positions;
    reference_position = other.reference_position;
    SPDLOG_DEBUG("Particle assigned by copy!");
    return *this;
}

