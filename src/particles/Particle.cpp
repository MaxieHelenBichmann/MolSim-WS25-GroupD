Particle::Particle(Particle&& other) noexcept {
    x = other.x;
    v = other.v;
    f = other.f;
    epsilon = other.epsilon;
    sigma = other.sigma;
    old_x = other.old_x;
    old_f = other.old_f;
    m = other.m;
    type = other.type;
    mirror_locations = other.mirror_locations;
    neighbors = other.neighbors;
    other.neighbors.fill(std::nullopt);
    SPDLOG_DEBUG("Particle generated by Move!");
}

Particle& Particle::operator=(Particle&& other) noexcept {
    if (this == &other) {
        return *this;
    }

    // Transfer scalar data
    x = other.x;
    v = other.v;
    f = other.f;
    epsilon = other.epsilon;
    sigma = other.sigma;
    old_x = other.old_x;
    old_f = other.old_f;
    m = other.m;
    type = other.type;
    mirror_locations = other.mirror_locations;

    // TRANSFER neighbors (Don't fill with nullopt!)
    neighbors = other.neighbors;

    // Clear the source's neighbors (Standard move semantics)
    other.neighbors.fill(std::nullopt);

    SPDLOG_DEBUG("Particle assigned by Move!");
    return *this;
}

Particle::~Particle() { SPDLOG_DEBUG("Particle destructed!"); }

std::string Particle::toString() const {
    std::stringstream stream;
    stream << "Particle: x:" << x << " old_x:" << old_x << " v: " << v << " f: " << f << " old_f: " << old_f
           << "epsilon: " << epsilon << "sigma:" << sigma << " type: " << type;
    return stream.str();
}

bool Particle::operator==(const Particle& other) const noexcept {
    return (x == other.x) and (old_x == other.old_x) and (v == other.v) and (f == other.f) and (type == other.type) and
           (m == other.m) and (old_f == other.old_f) and (epsilon == other.epsilon) and (sigma == other.sigma);
}

namespace mol_sim {
std::ostream& operator<<(std::ostream& stream, const Particle& p) {
    stream << p.toString();
    return stream;
}
}  // namespace mol_sim
